"""The clipper's view of the DB (a YAML overlay), its environment, and the subprocess runner.

The DB is the source of truth for creators, streams, prefs and for overrides of watchlist.yaml and each
profiles/<p>/profile.yaml, but the clipper reads YAML files and tracked repo files are never rewritten at runtime.
So `materialize()` writes an overlay under paths.runtime_dir() and every clipper subprocess gets
CLIPPER_PROFILES_DIR / CLIPPER_CONFIG pointing at it:

    runtime/watchlist.yaml                 repo watchlist.yaml + setting watchlist.overrides (verbatim copy when none)
    runtime/profiles/<p>/profile.yaml      repo profile.yaml + profiles.overrides (verbatim copy when none)
    runtime/profiles/<p>/creators.yaml     non-paused creators by (priority, id): {name, url, match?}
    runtime/profiles/<p>/live.yaml         non-paused streams by (priority, id): {name, url, topic_only, priority}
    runtime/profiles/<p>/prefs.yaml        the prefs.* settings (+ schedule_time = first scan time)
    runtime/profiles/<p>/<other files>     copies of everything else in the repo profile folder (learned-weights.yaml)

Overrides merge like clipper.config.load: a mapping merges one level per key, anything else replaces.
Files are only rewritten when their content changes (tmp + rename, so a running clipper sees the old or the new
file, never half of one). A clipper command that writes these files under the overlay (`creators add`,
`live add`, `prefs set`) only changes the overlay, and the next materialize() puts the DB's state back: the
dashboard is the only writer.

    materialize() -> [paths rewritten, relative to runtime_dir()]
    merge_config(base, overrides) -> dict
    watchlist_config() -> {base, overrides, effective}
    profile_config(name) -> {base, overrides, effective}          (profile.yaml level, before the watchlist merge)
    clipper_env(profile) -> dict                              os.environ + CLIPPER_PROFILE, CLIPPER_PROFILES_DIR,
        CLIPPER_CONFIG, PYTHONUNBUFFERED=1, PYTHONIOENCODING=utf-8, FISH_API_KEY, CLIPPER_TOP_HOOKS, PATH
    run_clipper(args, profile, *, timeout=None, on_line=None, cancel=None, module="clipper", argv=None,
                input=None, env=None, overlay=None) -> ProcResult
    run_bridge(op, payload, profile, *, timeout=600, on_line=None, cancel=None) -> dict      (BridgeError)
    ProcResult(returncode, stdout, stderr, duration, canceled=False, timed_out=False)
"""
import json
import os
import re
import shutil
import signal
import subprocess
import sys
import threading
import time
from pathlib import Path
from typing import NamedTuple

import yaml

from . import paths, store

MANAGED = ("profile.yaml", "creators.yaml", "live.yaml", "prefs.yaml")
SOURCES_HEADER = "# Generated by automate from the database (Dashboard → Quellen). Edits here are overwritten.\n"
PREFS_HEADER = "# Generated by automate from the database (Dashboard → Einstellungen). Edits here are overwritten.\n"
PREF_KEYS = ("voice", "videos_per_run", "max_videos_per_run", "hooks_per_video", "sources_per_day", "daily_max_minutes")
TERM_GRACE_S = 5.0  # SIGTERM -> SIGKILL
DRAIN_S = 5.0  # after the command exits, how long its output may take to drain before leftovers in its group are killed
STDERR_KEEP = 1_000_000  # bytes of stderr kept in ProcResult (the tail); stdout is kept whole (it carries the JSON)
READ_CHUNK = 65536

_materialize_lock = threading.Lock()


class ProcResult(NamedTuple):
    returncode: int
    stdout: str
    stderr: str
    duration: float
    canceled: bool = False
    timed_out: bool = False


class BridgeError(RuntimeError):
    """`python -m automate.bridge` failed: `message` is its error (or the last stderr line), `stderr` the full tail."""

    def __init__(self, message, stderr="", *, canceled=False, timed_out=False, returncode=None):
        super().__init__(message)
        self.message, self.stderr = message, stderr
        self.canceled, self.timed_out, self.returncode = canceled, timed_out, returncode


# ---------------------------------------------------------------- overlay

def merge_config(base, overrides):
    """The merge clipper.config.load applies to profile.yaml: mappings merge one level per key, the rest replaces."""
    out = dict(base or {})
    for k, v in (overrides or {}).items():
        out[k] = {**out[k], **v} if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def _read_yaml(path):
    if not path.exists():
        return {}
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def _dump(data):
    return yaml.safe_dump(data, sort_keys=False, allow_unicode=True, default_flow_style=False)


def watchlist_config():
    base = _read_yaml(paths.repo_watchlist())
    over = store.get_setting("watchlist.overrides") or {}
    return {"base": base, "overrides": over, "effective": merge_config(base, over)}


def profile_config(name):
    base = _read_yaml(paths.repo_profiles_dir() / name / "profile.yaml")
    row = store.get_profile(name)
    over = (row or {}).get("overrides") or {}
    return {"base": base, "overrides": over, "effective": merge_config(base, over)}


def _write(path, content, written):
    """Atomic write of `content` (str or bytes) unless the file already holds it."""
    path = Path(path)
    data = content.encode("utf-8") if isinstance(content, str) else content
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.{threading.get_ident()}.tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)
    written.append(path.relative_to(paths.runtime_dir()).as_posix())


def _merged_text(src, overrides):
    if not overrides:
        return src.read_text(encoding="utf-8") if src.exists() else "{}\n"
    return "# Generated by automate: the repository file merged with the dashboard's changes.\n" \
        + _dump(merge_config(_read_yaml(src), overrides))


def _prefs():
    s = store.all_settings()
    prefs = {k: s[f"prefs.{k}"] for k in PREF_KEYS}
    prefs["schedule_time"] = (s["schedule.scan_times"] or ["09:00"])[0]
    return prefs


def materialize():
    """Write the overlay from the repo files + DB; returns the files that changed (relative to runtime_dir())."""
    with _materialize_lock:
        written = []
        rt = paths.ensure_data_dir() / "runtime"
        watchlist = _merged_text(paths.repo_watchlist(), store.get_setting("watchlist.overrides"))
        _write(paths.runtime_watchlist(), watchlist, written)
        repo = paths.repo_profiles_dir()
        rows = {p["name"]: p for p in store.list_profiles()}
        names = sorted({p.name for p in repo.iterdir() if p.is_dir()} | set(rows) if repo.is_dir() else set(rows))
        prefs = PREFS_HEADER + _dump(_prefs())
        creators, streams = {}, {}
        for c in store.list_creators(include_paused=False):
            creators.setdefault(c["profile"], []).append(
                {"name": c["name"], "url": c["url"], **({"match": c["match"]} if c["match"] != "any" else {})})
        for s in store.list_streams(include_paused=False):
            streams.setdefault(s["profile"], []).append(
                {"name": s["name"], "url": s["url"], "topic_only": bool(s["topic_only"]), "priority": s["priority"]})
        out_root = paths.runtime_profiles_dir()
        out_root.mkdir(parents=True, exist_ok=True)
        for name in names:
            d, src = out_root / name, repo / name
            _write(d / "profile.yaml", _merged_text(src / "profile.yaml", (rows.get(name) or {}).get("overrides")),
                   written)
            _write(d / "creators.yaml", SOURCES_HEADER + _dump({"creators": creators.get(name, [])}), written)
            _write(d / "live.yaml", SOURCES_HEADER + _dump({"streams": streams.get(name, [])}), written)
            _write(d / "prefs.yaml", prefs, written)
            extras = {f.name for f in src.iterdir() if f.is_file() and f.name not in MANAGED} if src.is_dir() else set()
            for fname in sorted(extras):  # e.g. learned-weights.yaml, written there by a posting setup
                _write(d / fname, (src / fname).read_bytes(), written)
            for f in d.iterdir():
                if f.is_file() and f.name not in MANAGED and f.name not in extras and not f.name.startswith("."):
                    f.unlink()
                    written.append(f.relative_to(rt).as_posix())
        for d in out_root.iterdir():
            if d.is_dir() and d.name not in names:
                shutil.rmtree(d)
                written.append(d.relative_to(rt).as_posix())
        return written


# ---------------------------------------------------------------- environment

def clipper_env(profile):
    """The environment of a clipper (or bridge) subprocess for `profile`. The DB's Fish key and top-hooks setting
    win over the repo's .env (which the clipper reads with setdefault): an empty FISH_API_KEY means "no key"; a
    FISH_API_KEY exported in the server's own environment is kept while the dashboard has none."""
    env = dict(os.environ)
    env.update(CLIPPER_PROFILE=profile, CLIPPER_PROFILES_DIR=str(paths.runtime_profiles_dir()),
               CLIPPER_CONFIG=str(paths.runtime_watchlist()), PYTHONUNBUFFERED="1", PYTHONIOENCODING="utf-8")
    fish = store.get_secret("fish_api_key")
    if fish:
        env["FISH_API_KEY"] = fish
    elif not os.environ.get("FISH_API_KEY"):
        env["FISH_API_KEY"] = ""
    env["CLIPPER_TOP_HOOKS"] = str(int(store.get_setting("render.top_hooks") or 0))
    here = str(Path(sys.executable).parent)
    parts = [p for p in env.get("PATH", "").split(os.pathsep) if p and p != here]
    env["PATH"] = os.pathsep.join([here, *parts])
    return env


# ---------------------------------------------------------------- subprocesses

def _kill_group(proc, sig):
    try:
        os.killpg(proc.pid, sig)
    except (ProcessLookupError, PermissionError):
        pass


def _stop(proc):
    """SIGTERM the whole process group (ffmpeg, yt-dlp children too), SIGKILL after a grace period."""
    _kill_group(proc, signal.SIGTERM)
    try:
        proc.wait(TERM_GRACE_S)
    except subprocess.TimeoutExpired:
        _kill_group(proc, signal.SIGKILL)
        proc.wait()


class _Reader(threading.Thread):
    """Drains one pipe (raw reads, so output shows up as soon as it's written and the child never blocks on a full
    pipe) and hands every line to `emit`; '\r' (progress bars) ends a line too."""

    def __init__(self, pipe, emit, keep=None):
        super().__init__(daemon=True)
        self.pipe, self.emit, self.keep = pipe, emit, keep
        self.chunks, self.size = [], 0

    def _line(self, raw):
        if raw.strip():
            self.emit(raw.decode("utf-8", errors="replace"))

    def run(self):
        """Only this thread closes the pipe, and only at EOF: closing it from outside while a read is pending would
        let a later file reuse the descriptor under this reader."""
        buf, fd = b"", self.pipe.fileno()
        while True:
            try:
                chunk = os.read(fd, READ_CHUNK)
            except OSError:
                break
            if not chunk:
                break
            self.chunks.append(chunk)
            self.size += len(chunk)
            if self.keep and self.size > 2 * self.keep:
                data = b"".join(self.chunks)[-self.keep:]
                self.chunks, self.size = [data], len(data)
            if self.emit:
                *lines, buf = re.split(rb"\r\n|\r|\n", buf + chunk)
                for raw in lines:
                    self._line(raw)
                if len(buf) > READ_CHUNK:  # a huge line without a break: pass it on in pieces
                    self._line(buf)
                    buf = b""
        if self.emit:
            self._line(buf)
        self.pipe.close()

    def text(self):
        data = b"".join(self.chunks)
        return (data[-self.keep:] if self.keep else data).decode("utf-8", errors="replace")


def run_clipper(args, profile, *, timeout=None, on_line=None, cancel=None, module="clipper", argv=None, input=None,
                env=None, overlay=None):
    """Run `python -m <module> <args>` (or exactly `argv`) in ROOT, in its own process group, with clipper_env(profile).

    stdout and stderr are captured separately (stdout whole, stderr's last STDERR_KEEP bytes) and every line of
    either is passed to `on_line(str)` as it arrives (one call at a time; '\\r' progress updates count as lines;
    undecodable bytes become U+FFFD). When `cancel` (a threading.Event) is set or `timeout` seconds pass, the whole
    process group gets SIGTERM, then SIGKILL; the result says so (canceled / timed_out). Detached processes the
    command starts in their own session (live recorders) are not touched. stdin is /dev/null unless `input`
    (str or bytes) is given. `overlay` (default: True unless `argv` is given) runs materialize() first; `env`
    entries are added on top of clipper_env(profile).
    """
    if overlay if overlay is not None else argv is None:
        materialize()
    cmd = list(argv) if argv is not None else [sys.executable, "-m", module, *map(str, args)]
    full_env = clipper_env(profile)
    full_env.update(env or {})
    lock = threading.Lock()

    def emit(line):
        if on_line:
            with lock:
                try:
                    on_line(line)
                except Exception:  # a broken callback must not kill the reader (and with it the child's pipe)
                    pass

    start = time.monotonic()
    proc = subprocess.Popen(cmd, cwd=paths.ROOT, env=full_env, stdin=subprocess.PIPE if input is not None else
                            subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE, start_new_session=True)
    out, err = _Reader(proc.stdout, emit), _Reader(proc.stderr, emit, keep=STDERR_KEEP)
    out.start()
    err.start()
    if input is not None:
        data = input.encode("utf-8") if isinstance(input, str) else input

        def feed():
            try:
                proc.stdin.write(data)
                proc.stdin.close()
            except (BrokenPipeError, OSError):
                pass
        threading.Thread(target=feed, daemon=True).start()
    canceled = timed_out = False
    try:
        while True:
            try:
                proc.wait(0.2)
                break
            except subprocess.TimeoutExpired:
                pass
            if cancel is not None and cancel.is_set():
                canceled = True
            elif timeout is not None and time.monotonic() - start > timeout:
                timed_out = True
            if canceled or timed_out:
                _stop(proc)
                break
    except BaseException:
        _stop(proc)
        raise
    finally:
        for r in (out, err):
            r.join(DRAIN_S)
        if out.is_alive() or err.is_alive():  # a leftover member of the group still holds the pipe
            _kill_group(proc, signal.SIGKILL)
            for r in (out, err):
                r.join(2)
        # still alive: a process outside the group (started detached) inherited the pipe; its reader finishes and
        # closes the pipe when that process exits, and the result below holds what was read until now
    return ProcResult(proc.returncode, out.text(), err.text(), round(time.monotonic() - start, 3), canceled, timed_out)


def run_bridge(op, payload, profile, *, timeout=600, on_line=None, cancel=None):
    """`python -m automate.bridge <op>` with `payload` as JSON on stdin -> its JSON result (a dict)."""
    res = run_clipper([op], profile, module="automate.bridge", input=json.dumps(payload), timeout=timeout,
                      on_line=on_line, cancel=cancel)
    if res.canceled or res.timed_out:
        raise BridgeError("abgebrochen" if res.canceled else f"Zeitüberschreitung nach {timeout} s", res.stderr,
                          canceled=res.canceled, timed_out=res.timed_out, returncode=res.returncode)
    try:
        data = json.loads(res.stdout)
    except ValueError:
        data = None
    if res.returncode != 0 or not isinstance(data, dict):
        tail = [x for x in res.stderr.strip().splitlines() if x.strip()]
        msg = (data or {}).get("error") if isinstance(data, dict) else None
        raise BridgeError(msg or (tail[-1] if tail else f"bridge {op} exited with {res.returncode}"), res.stderr,
                          returncode=res.returncode)
    return data
